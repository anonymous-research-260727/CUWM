TEMPLATE2 = """
You are a prompt expert. Your task is to write a prompt for Qwen-image-edit that enables it to generate the next frame of a Word screenshot based on the previous one. I will provide Image 1 (the input image for Qwen), Image 2 (the desired output image), the user’s action, and a structured JSON generated by GPT-5 containing detailed descriptions of both images and their differences.

Based on this information, craft a clear, detailed, and specific prompt that:

1. Incorporates the user’s action naturally into the instruction.
2. Precisely describes the visual content that should appear in the generated image, including layout, text, interface elements, and formatting details.
3. Emphasizes all changes made relative to Image 1, clearly identifying their approximate positions and visual locations within the interface (e.g., toolbar, main document area, dialog box, etc.).
4. Reflects any additions, deletions, or modifications indicated in the structured JSON.
5. Uses concise, vivid, and unambiguous language to help Qwen-image-edit accurately reproduce the next frame.

The final output must be a single, coherent prompt (no longer than 500 words) written in natural, instructive English, with no explanations, titles, formatting markers, or extra content — only the final prompt text itself.
"""



def build_qwen_edit_json_from_word_frames(
    p1_path: str,
    p2_path: str,
    action_text: str,
    engine: str = "gpt-5-chat-20251003",
):
    """
    使用两帧 Word 截图(P1, P2) + 动作(action)，调用 GPT 模型，
    让其根据指定中文 Prompt 产出给 Qwen-image-edit 用的 JSON。

    参数:
        p1_path (str): 图一(上一帧)的本地路径。
        p2_path (str): 图二(目标帧)的本地路径。
        action_text (str): 动作描述，必须符合 SUPPORTED_ACTIONS_WORD 中的格式，
                           例如: "type(coordinate=[300,200], keys='Hello')"
        engine (str): 使用的模型引擎名称，默认 "gpt-4o-20240513"，
                      将来可以替换为 GPT-5 对应的 engine 名称。

    返回:
        dict: GPT 返回的 JSON 解析结果。如果解析失败，返回原始文本字符串。
    """

    full_prompt = (
        TEMPLATE
        + "\n\nSpecific input is as follows:\n"
        + "- Image 1: See the first image.\n"
        + "- Image 2: See the second image.\n"
        + f"- Action: {action_text}\n\n"
        + "Based on the above information, directly output the required JSON."
    )


    # 编码两张图片
    p1_url = encode_image(p1_path)
    p2_url = encode_image(p2_path)

    # 构造多模态 messages
    messages = [
        {
            "role": "user",
            "content": [
                {"type": "text", "text": full_prompt},
                {"type": "image_url", "image_url": {"url": p1_url}},
                {"type": "image_url", "image_url": {"url": p2_url}},
            ],
        }
    ]

    # 调用 GPT 模型
    response = get_chat_completion(engine=engine, messages=messages)

    # 解析内容
    msg = response.choices[0].message
    if isinstance(msg, dict):
        content = msg.get("content")
    else:
        content = msg.content

    if isinstance(content, str):
        raw_text = content
    elif isinstance(content, list) and len(content) > 0:
        raw_text = "".join(c.get("text", "") for c in content if isinstance(c, dict))
    else:
        raw_text = ""

    # 尝试解析 JSON
    try:
        result =  json.loads(raw_text)
    except json.JSONDecodeError:
        result = raw_text

    
    # Call 2
    if isinstance(result, dict):
        action = result.get("action", "")
    else:
        print("解析 JSON 失败，无法提取 action。")
        action = ""

    full_prompt_2 = (
        TEMPLATE2
        + "\n\nSpecific input is as follows:\n"
        + "- Image 1: See the first image.\n"
        + "- Image 2: See the second image.\n"
        + f"- Action: {action_text}: {action}\n\n"
        + f"- GPT-5 Generated JSON: {result}\n\n"
        + "Based on the above information, directly output the final prompt text for Qwen-image-edit."
    )


    messages_2 = [
        {
            "role": "user",
            "content": [
                {"type": "text", "text": full_prompt_2},
                {"type": "image_url", "image_url": {"url": p1_url}},
                {"type": "image_url", "image_url": {"url": p2_url}},
            ],
        }
    ]

    # 调用 GPT 模型
    response_2 = get_chat_completion(engine=engine, messages=messages_2)

    # 解析内容
    msg = response_2.choices[0].message
    if isinstance(msg, dict):
        content_2 = msg.get("content")
    else:
        content_2 = msg.content

    if isinstance(result, dict):
        result["gpt5_prompt_for_json_generation"] = full_prompt
        result["gpt5_prompt_for_prompt_generation"] = full_prompt_2
        result["qwen_prompt"] = content_2

    return result, content_2


def process_word_pair(folder):
    """
    读取指定文件夹下的 action.txt、prev.png、next.png，
    调用 build_qwen_edit_json_from_word_frames()，
    并将结果保存到 label.json 与 qwen_prompt.txt。

    参数:
        folder (str): 文件夹路径，例如 r"data/word_1_4/pair_01"
    """
    # 1. 读 action.txt
    action_path = os.path.join(folder, "action.txt")
    with open(action_path, "r", encoding="utf-8") as f:
        # 如果 action.txt 里只有一行，就直接读一整块
        action = f.read().strip()
        # 如果你是「一行一个 action」，想只取第一行，可以用：
        # action = f.readline().strip()

    # 2. 构造图片路径
    p1_path = os.path.join(folder, "prev.png")
    p2_path = os.path.join(folder, "next.png")

    # 3. 调用之前写好的函数
    json_result, qwen_prompt = build_qwen_edit_json_from_word_frames(
        p1_path=p1_path,
        p2_path=p2_path,
        action_text=action,
    )


    # 5. 保存 JSON 文件
    if isinstance(json_result, dict):
        label_path = os.path.join(folder, "label.json")
        with open(label_path, "w", encoding="utf-8") as f:
            json.dump(json_result, f, ensure_ascii=False, indent=2)
    else:
        print(f"Warning: JSON 解析失败，未保存 label.json，内容为原始文本：\n{json_result}")
        with open(os.path.join(folder, "failed_label.txt"), "w", encoding="utf-8") as f:
            f.write(json_result)

    # 6. 保存 qwen_prompt 到文本文件
    prompt_path = os.path.join(folder, "qwen_prompt.txt")
    with open(prompt_path, "w", encoding="utf-8") as f:
        f.write(qwen_prompt)

    if "failed_label.txt" in os.listdir(folder):
        os.remove(os.path.join(folder, "failed_label.txt"))

    # 7. 打印结果
    # print(f"=== JSON 结果 ===\n{json.dumps(json_result, ensure_ascii=False, indent=2)}")
    # print(f"\n=== 已保存到 ===\n{label_path}\n{prompt_path}")



def find_all_valid_pairs(root_dir="data", skip_if_exists=True):
    """
    Recursively traverse all folders under `root_dir`.
    Return a list of folders containing 'action', 'prev', and 'next' files.
    
    If skip_if_exists=True, skip folders that already contain
    'qwen_prompt' or 'label' files.
    """
    valid_folders = []

    for dirpath, dirnames, filenames in os.walk(root_dir):
        file_set = set(f.lower() for f in filenames)

        has_action = any(f.startswith("action") for f in file_set)
        has_prev = any(f.startswith("prev") for f in file_set)
        has_next = any(f.startswith("next") for f in file_set)

        if has_action and has_prev and has_next:
            if skip_if_exists and (
                any(f.startswith("qwen_prompt") for f in file_set)
                or any(f.startswith("label") for f in file_set)
            ):
                # skip this folder
                continue
            valid_folders.append(dirpath)

    return valid_folders


