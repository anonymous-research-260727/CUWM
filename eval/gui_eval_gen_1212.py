import os
from tqdm import tqdm
import json
from cloudgpt_aoai import get_chat_completion, encode_image
from concurrent.futures import ProcessPoolExecutor, as_completed


INSTRUCTIONAL_ACCURACY_SCORE_SYS_PROMPT = """
You are an expert in evaluating the performance of an **Office Emulator**.
The Office Emulator is designed to interact with **Microsoft Office applications (Word, Excel, PowerPoint)** and predict UI changes based on human instructions.

**Inputs:**

* **Current UI Screenshot**: The current state of the Office application interface.
* **Next UI Screenshot**: The UI state generated by the Office Emulator, representing the predicted next state after executing the instruction.
* **Human Instruction**: The user instruction applied to the current Office UI (e.g., editing text, formatting cells, inserting objects, changing layouts).

**Your Task:**
Determine whether the Office Emulator **successfully predicts the correct next UI state** based on:

* Correct execution of the human instruction
* Accurate changes in content, layout, formatting, or selection
* Consistency with standard Office application behavior and UI logic

Evaluate whether the predicted next UI screenshot is **correct and reasonable** given the current UI and the instruction.

**IMPORTANT**
Format your response strictly as a JSON object:

```json
{
  "Thoughts": "<your reasoning and evaluation process>",
  "Status": "success" or "failure"
}
```

"""


def evaluate_one(
    current_ui_image_path: str,
    next_ui_image_path: str,
    instruction_text: str,
    next_ui_gt_image_path: str = None,
    engine: str = "gpt-5-chat-20251003",
) -> dict:
    if next_ui_gt_image_path:
        ret_save_path = next_ui_image_path.replace(".png", "_llm_eval_with_gt_next.json")
    else:
        ret_save_path = next_ui_image_path.replace(".png", "_llm_eval_wo_gt_next.json")
    
    if os.path.exists(ret_save_path):
        with open(ret_save_path, "r") as f:
            result = json.load(f)
        if result["Status"] == "success":
            return 1
        elif result["Status"] == "failure":
            return 0
    
    current_ui_image_url = encode_image(current_ui_image_path)
    next_ui_image_url = encode_image(next_ui_image_path)
    if next_ui_gt_image_path:
        next_ui_gt_image_url = encode_image(next_ui_gt_image_path)
        instruction_text += f" The ground truth next UI screenshot is provided here: See Image 3. Please use it as reference for your evaluation."
    
    
    if next_ui_gt_image_path:
        full_prompt = (
            INSTRUCTIONAL_ACCURACY_SCORE_SYS_PROMPT
            + "\n\n"
            + "Current UI Screenshot: See Image 1.\n"
            + "Next UI Screenshot: See Image 2.\n"
            + "Ground Truth Next UI Screenshot: See Image 3.\n"
            + f"Human Instruction: {instruction_text}\n\n"
        )
        messages = [
            {
                "role": "user",
                "content": [
                    {"type": "text", "text": full_prompt},
                    {"type": "image_url", "image_url": {"url": current_ui_image_url}},
                    {"type": "image_url", "image_url": {"url": next_ui_image_url}},
                    {"type": "image_url", "image_url": {"url": next_ui_gt_image_url}},
                ],
            }
        ]
    else: 
        full_prompt = (
            INSTRUCTIONAL_ACCURACY_SCORE_SYS_PROMPT
            + "\n\n"
            + "Current UI Screenshot: See Image 1.\n"
            + "Next UI Screenshot: See Image 2.\n"
            + f"Human Instruction: {instruction_text}\n\n"
        )
        messages = [
            {
                "role": "user",
                "content": [
                    {"type": "text", "text": full_prompt},
                    {"type": "image_url", "image_url": {"url": current_ui_image_url}},
                    {"type": "image_url", "image_url": {"url": next_ui_image_url}},
                ],
            }
        ]
    
    response = get_chat_completion(engine=engine, messages=messages)
    content = response.choices[0].message.content
    content = content.replace("```json", "").replace("```", "").strip()
    # print(content)
    
    result = json.loads(content)
    ret = None
    
    if result["Status"] == "success":
        ret = 1
    elif result["Status"] == "failure":
        ret = 0

    
    with open(ret_save_path, "w") as f:
        json.dump(result, f, indent=2)
    
    return ret
    
def get_action_instruction(action_file, label_file):
    with open(action_file, "r") as f:
        action = f.readlines()
    
    with open(label_file, "r") as f:
        labels = json.load(f)
        action_nl = labels["action"]
    
    return f"{action_nl} ({action})"
    
def evaluate_single_sample(eval_dir, compare_key, use_gt_image):
    """Helper function to evaluate a single sample (for parallel processing)"""
    current_ui_image_path = os.path.join(eval_dir, "prev.png")
    next_ui_image_path = os.path.join(eval_dir, compare_key)
    action_file = os.path.join(eval_dir, "action.txt")
    label_file = os.path.join(eval_dir, "label.json")
    instruction_text = get_action_instruction(action_file, label_file)
    
    if use_gt_image:
        next_ui_gt_image_path = os.path.join(eval_dir, "next.png")
        score = evaluate_one(
            current_ui_image_path,
            next_ui_image_path,
            instruction_text,
            next_ui_gt_image_path,
        )
    else:
        score = evaluate_one(
            current_ui_image_path,
            next_ui_image_path,
            instruction_text,
        )
    
    return score

def evaluate_all(data_root, compare_key, use_gt_image=False, max_workers=8):
    all_eval_dirs = []
    for dirpath, dirnames, filenames in os.walk(data_root):
        # print(dirpath, dirnames, filenames)
        if compare_key in filenames and "action.txt" in filenames and "label.json" in filenames:
            if use_gt_image:
                if "next.png" in filenames:
                    all_eval_dirs.append(dirpath)
            else:
                all_eval_dirs.append(dirpath)
    print(f"Found {len(all_eval_dirs)} samples to evaluate.")
    
    if len(all_eval_dirs) == 0:
        return 0, 0
    
    all_score = 0
    with ProcessPoolExecutor(max_workers=max_workers) as executor:
        futures = {
            executor.submit(evaluate_single_sample, eval_dir, compare_key, use_gt_image): eval_dir 
            for eval_dir in all_eval_dirs
        }
        
        for future in tqdm(as_completed(futures), total=len(all_eval_dirs), desc="Evaluating samples"):
            try:
                score = future.result()
                all_score += score
            except Exception as e:
                print(f"Error evaluating {futures[future]}: {e}")
    
    return all_score / len(all_eval_dirs), len(all_eval_dirs)

    
